"""Generate the whole dataset deterministically:  uv run python -m dataset.generate"""

from __future__ import annotations

import json
import random
import shutil
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from dataset import freeze
from dataset.documents import write_claim_documents
from dataset.policies import write_all
from dataset.scenarios import PLAN, SEED, generate

DATA = Path(__file__).resolve().parent.parent / "data"
DEV_SIZE = 40
INTERNAL = ("state", "zone", "other_object", "side", "has_police")


def assign_splits(claims: list[dict[str, Any]]) -> None:
    rng = random.Random(SEED)
    units: dict[str, list[list[dict[str, Any]]]] = defaultdict(list)
    by_pair: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for c in claims:
        by_pair[c["pair_id"]].append(c)
    for members in by_pair.values():
        kind = "fraud_duplicate" if len(members) > 1 else members[0]["scenario"]["type"]
        units[kind].append(members)
    dev: list[dict[str, Any]] = []
    for kind in PLAN:
        pool = sorted(units[kind], key=lambda m: m[0]["claim_id"])
        rng.shuffle(pool)
        target = round(0.2 * PLAN[kind])
        taken = 0
        for members in pool:
            if taken >= target:
                break
            dev += members
            taken += len(members)
    singles_clean = [
        c
        for c in dev
        if c["scenario"]["type"] == "approve_clean"
        and c["pair_id"] == c["claim_id"]
        and len(by_pair[c["pair_id"]]) == 1
    ]
    while len(dev) > DEV_SIZE and singles_clean:
        dev.remove(singles_clean.pop())
    dev_ids = {c["claim_id"] for c in dev}
    for c in claims:
        c["split"] = "dev" if c["claim_id"] in dev_ids else "test"


def distribution(claims: list[dict[str, Any]]) -> str:
    def table(title: str, counter: Counter[str]) -> str:
        rows = "\n".join(f"| {k} | {v} |" for k, v in sorted(counter.items()))
        return f"### {title}\n\n| Value | Claims |\n| --- | --- |\n{rows}\n"

    parts = [
        "# Dataset label distribution\n",
        f"Generated by `dataset.generate` (seed {SEED}). {len(claims)} claims.\n",
        table("Decision", Counter(c["decision"] for c in claims)),
        table("Scenario", Counter(c["scenario"]["type"] for c in claims)),
        table(
            "Fraud flag",
            Counter(f for c in claims for f in c["fraud_flags"])
            + Counter({"(none)": sum(not c["fraud_flags"] for c in claims)}),
        ),
        table(
            "Document quality tier",
            Counter(c["doc_quality"]["degradation"] or "clean" for c in claims),
        ),
        table("Policy", Counter(c["policy_code"] for c in claims)),
        table("Split", Counter(c["split"] for c in claims)),
        table("Dev split by decision", Counter(c["decision"] for c in claims if c["split"] == "dev")),
        table("Test split by decision", Counter(c["decision"] for c in claims if c["split"] == "test")),
    ]
    return "\n".join(parts)


def main(data: Path = DATA) -> None:
    if data != DATA:
        data.mkdir(parents=True, exist_ok=True)
        shutil.copy(DATA / "seed_stats.json", data / "seed_stats.json")
    for sub in ("policies", "claims", "documents"):
        shutil.rmtree(data / sub, ignore_errors=True)
    pages = write_all(data / "policies")
    claims = generate(data)
    assign_splits(claims)
    for c in claims:
        c["documents"] = write_claim_documents(c, data / "documents")
        c["generator"] = {k: c.pop(k) for k in INTERNAL}
        out = data / "claims" / f"{c['claim_id']}.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(c, indent=2, sort_keys=True) + "\n")
    splits = {s: sorted(c["claim_id"] for c in claims if c["split"] == s) for s in ("dev", "test")}
    (data / "splits.json").write_text(json.dumps(splits, indent=2) + "\n")
    (data / "DISTRIBUTION.md").write_text(distribution(claims))
    freeze.write_manifest(data)
    print(f"policies pages: {pages}")
    print(f"claims: {len(claims)}  dev: {len(splits['dev'])}  test: {len(splits['test'])}")
    print(f"test set hash: {freeze.compute_testset_hash(data)}")


if __name__ == "__main__":
    main()
